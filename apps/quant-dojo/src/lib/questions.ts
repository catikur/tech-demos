const byId = new Map(QUESTIONS.map((question) => [question.id, question]));

export function questionById(id: string): Question | null {
  return byId.get(id) ?? null;
}

export function questionsFor(skill: SkillId, tier: QuestionTier): Question[] {
  return QUESTIONS.filter((question) => question.skill === skill && question.tier === tier);
}
